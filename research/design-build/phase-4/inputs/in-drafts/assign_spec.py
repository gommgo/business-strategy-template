SPEC = {}
KIMI = "адресат kimi удалён (Р75, Р80); смысл — claude-design 06 (Р68): проверить"

def put(prefix, text, default_note=""):
    for line in text.strip().splitlines():
        line = line.strip()
        if not line:
            continue
        parts = line.split("|")
        item, node = parts[0].strip(), parts[1].strip()
        note = parts[2].strip() if len(parts) > 2 else ""
        if default_note:
            note = f"{default_note}; {note}" if note else default_note
        key = f"{prefix}#{item}"
        assert key not in SPEC, key
        SPEC[key] = (node, note)

def rng(fmt, a, b, node, note=""):
    return "\n".join(f"{fmt.format(i)}|{node}|{note}" for i in range(a, b + 1))

